const BY_ID = new Map(GRAMMAR.map((g) => [g.id, g]));

export const grammarById = (id: string, custom: GrammarPoint[] = []): GrammarPoint | undefined =>
  BY_ID.get(id) ?? custom.find((g) => g.id === id);

function distance(a: string, b: string): number {
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    for (let j = 1; j <= b.length; j++)
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    prev = cur;
  }
  return prev[b.length];
}

/** Closest known ids for an unknown one (edit distance, substring matches first). */
export function suggestGrammar(id: string, custom: GrammarPoint[] = []): string[] {
  return [...GRAMMAR, ...custom]
    .map((g) => ({ id: g.id, d: g.id.includes(id) || id.includes(g.id) ? 0 : distance(id, g.id) }))
    .filter((x) => x.d <= Math.max(3, id.length / 3))
    .sort((a, b) => a.d - b.d)
    .slice(0, 4)
    .map((x) => x.id);
}
